/**
 * Strings with a FIGURE OR A TICKER BAKED INTO THEM can never match whole-node: "18.79M REX raised"
 * is a different string every minute. Rather than split a dozen call sites so the static words sit
 * in their own text node, a small set of ANCHORED patterns translates around the dynamic part.
 *
 * ⛔ Every pattern is anchored at both ends and the captured group is constrained to figures,
 * tickers and punctuation — never free text. That is what keeps the original safety rule intact: a
 * coin name, a wallet or anything a user typed still cannot be rewritten by accident, because it
 * could not match the shape in the first place.
 */
const NUM = '[\\d.,]+[KMB]?';
const PATTERNS = {
  es: [
    [new RegExp(`^(${NUM}\\s*\\S*) raised$`), '$1 recaudado'],
    [new RegExp(`^(${NUM}\\s*\\S*) to go$`), '$1 por recaudar'],
    [/^Buy (\$[A-Z0-9]{2,12})$/, 'Comprar $1'],
    [/^Sell (\$[A-Z0-9]{2,12})$/, 'Vender $1'],
    [/^Share (\$[A-Z0-9]{2,12})$/, 'Compartir $1'],
    [/^created (.{1,12}) ago by$/, 'creada hace $1 por'],
    [/^Balance: (.{1,24})$/, 'Saldo: $1'],
    [new RegExp(`^(${NUM}) payouts · (${NUM}) epochs$`), '$1 pagos · $2 épocas'],
    [/^Graduates at (.+) · then migrates price-continuously to an AMM with burned LP$/,
      'Se gradúa en $1 · luego migra con precio continuo a un AMM con LP quemada'],
    [/^(\d+) members?$/, '$1 miembros'],
    // ⛔ WAS /^Pays (.+)$/, which rewrote "Pays attention to detail" — the exact class of accident
    // the whole-node rule exists to prevent. The chip only ever says a percentage, so say that.
    [/^Pays (\d[\d.,]*%)$/, 'Paga $1'],
  ],
};

const KEY = 'rex_lang';
export const LANGS = [['en', 'EN'], ['es', 'ES']];
let lang = 'en';
try { const v = localStorage.getItem(KEY); if (v && DICT[v]) lang = v; } catch {}
export const getLang = () => lang;

const ATTRS = ['placeholder', 'title', 'aria-label'];
function translateIn(root) {
  const d = DICT[lang];
  if (!d || !root) return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    // Never touch what the user is typing, and never touch code or script content.
    acceptNode: (n) => {
      const p = n.parentElement;
      if (!p || p.closest('script,style,textarea,input,code,pre,[data-no-i18n]')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const hits = [];
  for (let n = w.nextNode(); n; n = w.nextNode()) {
    const raw = n.nodeValue;
    const trimmed = raw.trim();
    if (!trimmed) continue;
    let out = null;
    if (trimmed in d) out = d[trimmed];                 // whole-node match first
    else {
      // Then the anchored patterns, for strings with a figure or ticker inside them.
      for (const [re, rep] of (PATTERNS[lang] || [])) {
        if (re.test(trimmed)) { out = trimmed.replace(re, rep); break; }
      }
    }
    if (out === null) continue;
    hits.push([n, raw.replace(trimmed, out)]);
  }
  for (const [n, v] of hits) n.nodeValue = v;

  const el = root.nodeType === 1 ? root : document.body;
  for (const a of ATTRS) {
    for (const e of el.querySelectorAll(`[${a}]`)) {
      const v = e.getAttribute(a)?.trim();
      if (v && v in d) e.setAttribute(a, d[v]);
    }
  }
}

// Coalesced with a timer rather than requestAnimationFrame: rAF does not fire in a background tab,
// so a page opened in one — or restored from one — would sit there in English until it was focused,
// and the first sweep after boot would never run at all if the tab started hidden.
let queued = null;
function sweep() {
  if (queued) return;
  queued = setTimeout(() => { queued = null; translateIn(document.body); }, 16);
}

export function setLang(next) {
  if (!DICT[next] && next !== 'en') return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch {}
  document.documentElement.lang = next;
  // Going back to English means re-rendering from source, since the original words are gone from the
  // DOM once they have been replaced. Re-running the router is cheaper and more reliable than
  // keeping a reverse map in step with every edit.
  location.reload();
}

export function startI18n() {
  document.documentElement.lang = lang;
  if (lang === 'en') return;
  sweep();
  new MutationObserver(sweep).observe(document.body, { childList: true, subtree: true });
}
